class BuildError(ValueError):
    """A discovered content file is malformed."""


def read_yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def text(value: Any) -> str:
    return value if isinstance(value, str) else ""


def slug_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(v) for v in value if isinstance(v, (str, int, float))]


def rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def first_existing(*paths: Path) -> str | None:
    for path in paths:
        if path.exists():
            return rel(path)
    return None


def extract_title_md(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip()
    return path.stem


def extract_summary_md(path: Path) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    for line in lines:
        s = line.strip()
        if not s or s.startswith("#") or s.startswith(">") or s.startswith("```") or s.startswith("|") or s.startswith("-") or s.startswith("*") or s.startswith("<!--"):
            continue
        return re.sub(r"\s+", " ", s)[:220]
    return ""


def add(items: list[dict[str, Any]], item: dict[str, Any]) -> None:
    item.setdefault("tags", [])
    item.setdefault("links", [])
    item.setdefault("related", [])
    item.setdefault("concerns", [])
    item.setdefault("status", "")
    item["uid"] = f"{item['family']}:{item['kind']}:{item['id']}"
    items.append(item)


def discover_design_patterns(items: list[dict[str, Any]]) -> None:
    root = REPO_ROOT / "design-patterns"
    for path in sorted((root / "content").glob("*.yaml")):
        data = read_yaml(path) or {}
        pid = text(data.get("id")) or path.stem
        base = root / pid
        links = []
        for label, p in [("README", base / "README.md"), ("Quiz", base / "quiz_guide.md"), ("Page", base / "index.html")]:
            if p.exists():
                links.append({"label": label, "path": rel(p)})
        add(items, {
            "id": pid,
            "title": text(data.get("name")) or pid,
            "family": "design-patterns",
            "kind": text(data.get("category")) or "pattern",
            "summary": text(data.get("intent")),
            "intent": text(data.get("intent")),
            "problem": text(data.get("problem")),
            "use_when": slug_list(data.get("forces")),
            "tradeoffs": data.get("consequences"),
            "participants": data.get("participants"),
            "related": slug_list(data.get("related_architecture")),
            "tags": [text(data.get("category")), "design-pattern"],
            "source": rel(path),
            "links": links,
        })


def discover_architecture(items: list[dict[str, Any]]) -> None:
    root = REPO_ROOT / "architecture" / "content"
    for kind, folder in [("style", "styles"), ("tactic", "tactics"), ("quality-attribute", "quality-attributes")]:
        for path in sorted((root / folder).glob("*.yaml")):
            data = read_yaml(path) or {}
            aid = text(data.get("id")) or path.stem
            related = slug_list(data.get("tactics")) + slug_list(data.get("related_styles")) + slug_list(data.get("related_tactics")) + slug_list(data.get("quality_attributes"))
            add(items, {
                "id": aid,
                "title": text(data.get("name")) or aid,
                "family": "architecture",
                "kind": kind,
                "summary": text(data.get("summary")) or text(data.get("definition")),
                "decision": text(data.get("decision")),
                "use_when": slug_list(data.get("use_when")) or slug_list(data.get("stimulus")),
                "avoid_when": slug_list(data.get("avoid_when")),
                "tradeoffs": data.get("tradeoffs"),
                "components": data.get("components"),
                "measure": slug_list(data.get("measure")) or slug_list(data.get("response")),
                "mechanism": text(data.get("mechanism")),
                "related": list(dict.fromkeys(related)),
                "tags": [kind, "architecture"],
                "source": rel(path),
                "links": [{"label": "Catalogue", "path": "architecture/CATALOGUE.md"}, {"label": "Graph page", "path": "visual/architecture/index.html"}],
            })
    catalogue_path = REPO_ROOT / "architecture" / "content" / "catalogue.yaml"
    catalogue = read_yaml(catalogue_path) or {}
    for scenario in catalogue.get("scenarios", []) or []:
        sid = text(scenario.get("id"))
        if not sid:
            continue
        artifacts = {k: text(scenario.get(k)) for k in ("path", "hints", "solution", "rubric") if text(scenario.get(k))}
        links = [{"label": k.title(), "path": v} for k, v in artifacts.items()]
        status = text(scenario.get("status")) or "scenario"
        add(items, {
            "id": sid,
            "title": text(scenario.get("title")) or sid,
            "family": "scenarios",
            "kind": "scenario",
            "status": status,
            "summary": f"Scenario {sid}: {text(scenario.get('title')) or sid}",
            "artifacts": artifacts,
            "related": slug_list(scenario.get("patterns")),
            "tags": ["scenario", status],
            "source": rel(catalogue_path),
            "links": links,
        })


def discover_yaml_family(items: list[dict[str, Any]], family: str, content_dir: Path, kind: str) -> None:
    for path in sorted(content_dir.glob("*.yaml")):
        data = read_yaml(path) or {}
        fid = text(data.get("id")) or path.stem
        base = content_dir.parent / fid
        links = []
        for label, p in [("README", base / "README.md"), ("Quiz", base / "quiz_guide.md"), ("Page", base / "index.html"), ("Glossary", base / "glossary.json")]:
            if p.exists():
                links.append({"label": label, "path": rel(p)})
        if family == "proofs":
            vpage = REPO_ROOT / "visual" / "proofs" / f"{fid}.html"
            if vpage.exists():
                links.append({"label": "Proof graph", "path": rel(vpage)})
        tags = [family, kind, *slug_list(data.get("tags"))]
        concerns = slug_list(data.get("concerns")) or slug_list(data.get("quality_attributes"))
        add(items, {
            "id": fid,
            "title": text(data.get("title")) or text(data.get("name")) or fid,
            "family": family,
            "kind": kind,
            "status": text(data.get("status")),
            "summary": text(data.get("summary")) or text(data.get("statement")) or text(data.get("intent")),
            "problem": text(data.get("problem")) or text(data.get("statement")),
            "tradeoffs": data.get("tradeoffs") or data.get("consequences"),
            "related": slug_list(data.get("claim_ids")) + slug_list(data.get("related")) + slug_list(data.get("related_architecture")),
            "concerns": concerns,
            "tags": [t for t in tags if t],
            "source": rel(path),
            "links": links,
        })


def discover_papers(items: list[dict[str, Any]]) -> None:
    for path in sorted((REPO_ROOT / "papers" / "content").glob("*.yaml")):
        data = read_yaml(path) or {}
        arxiv = text(data.get("arxiv_id")) or path.stem.removeprefix("arxiv-")
        base = REPO_ROOT / "papers" / arxiv
        links = [{"label": label, "path": rel(base / name)} for label, name in [("Overview", "README.md"), ("Page", "index.html"), ("Concepts", "concepts.json")] if (base / name).exists()]
        vmap = REPO_ROOT / "visual" / "concepts" / f"arxiv-{arxiv}.html"
        if vmap.exists():
            links.append({"label": "Concept map", "path": rel(vmap)})
        add(items, {
            "id": arxiv,
            "title": text(data.get("title")) or arxiv,
            "family": "papers",
            "kind": "paper",
            "summary": text(data.get("abstract"))[:220],
            "tags": ["paper"],
            "source": rel(path),
            "links": links,
        })


def discover_providers(items: list[dict[str, Any]]) -> None:
    for path in sorted((REPO_ROOT / "providers" / "content").glob("*.yaml")):
        data = read_yaml(path) or {}
        pid = text(data.get("id")) or path.stem
        providers = data.get("providers") if isinstance(data.get("providers"), dict) else {}
        links = [{"label": "Matrix", "path": "providers/matrix.md"}, {"label": "Page", "path": "providers/index.html"}]
        add(items, {
            "id": pid,
            "title": text(data.get("name")) or pid,
            "family": "providers",
            "kind": "mapping",
            "summary": text(data.get("summary")),
            "providers": {k: v.get("services") if isinstance(v, dict) else v for k, v in providers.items()},
            "tags": ["provider", "mapping"],
            "source": rel(path),
            "links": links,
        })


def discover_pattern_docs(items: list[dict[str, Any]]) -> None:
    root = REPO_ROOT / "patterns"
    generated = {"PATTERNS_INDEX.md"}
    for path in sorted(root.glob("*.md")):
        if path.name in {"README.md"} | generated:
            continue
        title = extract_title_md(path)
        kind = "template" if "template" in path.stem.lower() else ("index" if "index" in path.stem.lower() else "pattern-doc")
        add(items, {
            "id": path.stem,
            "title": title,
            "family": "patterns-library",
            "kind": kind,
            "summary": extract_summary_md(path),
            "tags": ["pattern-doc", kind],
            "source": rel(path),
            "links": [{"label": "Open", "path": rel(path)}],
        })
    data_path = REPO_ROOT / "data" / "patterns.json"
    if data_path.exists():
        data = json.loads(data_path.read_text(encoding="utf-8"))
        for pattern in data.get("patterns", []) or []:
            pid = text(pattern.get("id"))
            if not pid:
                continue
            diagram = pattern.get("diagram") or {}
            links = []
            if text(diagram.get("file")):
                links.append({"label": "Diagram", "path": text(diagram.get("file"))})
            concerns = slug_list(pattern.get("concerns"))
            add(items, {
                "id": pid,
                "title": text(pattern.get("title")) or pid,
                "family": "pattern-catalogue",
                "kind": text(pattern.get("category")) or "pattern",
                "status": text(pattern.get("status")),
                "summary": text(pattern.get("problem"))[:220],
                "decision": text(pattern.get("decision")),
                "use_when": slug_list(pattern.get("use_when")),
                "avoid_when": slug_list(pattern.get("avoid_when")),
                "tradeoffs": pattern.get("tradeoffs"),
                "concerns": concerns,
                "tags": ["visual-pattern", *concerns],
                "source": rel(data_path),
                "links": links,
            })


def discover_surfaces(items: list[dict[str, Any]]) -> None:
    for path, fid, title, family, kind, summary in [
        (REPO_ROOT / "site" / "index.html", "site-explorer", "Content explorer", "site", "interactive", "Autogenerated local searchable catalogue of repository content."),
        (REPO_ROOT / "cards" / "index.html", "cards-review", "Card review", "review", "interactive", "Timed local review over the canonical card deck."),
        (REPO_ROOT / "visual" / "index.html", "visual-hub", "Visual review hub", "review", "interactive", "Concept maps, diagrams, architecture graph, and proof pages."),
        (REPO_ROOT / "architecture" / "CATALOGUE.md", "architecture-catalogue", "Architecture catalogue", "architecture", "catalogue", "Generated canonical architecture index."),
        (REPO_ROOT / "providers" / "matrix.md", "provider-matrix", "Provider matrix", "providers", "catalogue", "Generated cross-provider mapping matrix."),
        (REPO_ROOT / "design-patterns" / "INDEX.md", "design-pattern-index", "Design patterns index", "design-patterns", "catalogue", "Generated design pattern index."),
    ]:
        if path.exists():
            add(items, {"id": fid, "title": title, "family": family, "kind": kind, "summary": summary, "tags": [kind, family], "source": rel(path), "links": [{"label": "Open", "path": rel(path)}]})


def build_catalog() -> dict[str, Any]:
    items: list[dict[str, Any]] = []
    discover_design_patterns(items)
    discover_architecture(items)
    discover_yaml_family(items, "data-structures", REPO_ROOT / "data-structures" / "content", "data-structure")
    discover_yaml_family(items, "testing", REPO_ROOT / "testing" / "content", "testing-pattern")
    discover_yaml_family(items, "proofs", REPO_ROOT / "proofs" / "content", "proof")
    discover_papers(items)
    discover_providers(items)
    discover_pattern_docs(items)
    discover_surfaces(items)
    items.sort(key=lambda i: (i["family"], i["kind"], i["title"].lower(), i["id"]))
    families = sorted({i["family"] for i in items})
    kinds = sorted({i["kind"] for i in items})
    return {"schema_version": 1, "generated_by": "site/tools/build.py", "total": len(items), "families": families, "kinds": kinds, "items": items}


def patterns_index_md(catalog: dict[str, Any]) -> str:
    docs = [i for i in catalog["items"] if i["family"] == "patterns-library" and i["kind"] != "index"]
    docs = sorted(docs, key=lambda i: (0 if re.match(r"^\d+", i["id"]) else 1, i["id"]))
    lines = [
        "# Patterns library index",
        "",
        "> Generated by `site/tools/build.py`. Edit source files in `patterns/`, then rebuild the site.",
        "",
        "## Documents",
        "",
    ]
    for item in docs:
        path = item["links"][0]["path"] if item.get("links") else item.get("source", "")
        name = Path(path).name if path else item["id"]
        summary = item.get("summary") or ""
        suffix = f" — {summary}" if summary else ""
        lines.append(f"- [{item['title']}]({name}){suffix}")
    lines += [
        "",
        "## Interactive explorer",
        "",
        "- Local explorer: `just -f site/justfile serve` then open `http://localhost:8000/site/index.html`",
        "- Catalog data: `site/catalog.json`",
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_all() -> dict[Path, str]:
    catalog = build_catalog()
    catalog_json = json.dumps(catalog, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
    page = PAGE.replace("__CATALOG__", catalog_json.replace("</", "<\\/"))
    return {
        Path("catalog.json"): catalog_json,
        Path("index.html"): page,
        REPO_ROOT / "patterns" / "PATTERNS_INDEX.md": patterns_index_md(catalog),
    }


def write_all(root: Path = ROOT) -> list[Path]:
    written = []
    for relative, value in render_all().items():
        target = relative if relative.is_absolute() else root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(value, encoding="utf-8")
        written.append(target)
    return written


app = typer.Typer(help="Build the local interactive content explorer.")


@app.command()
def build(check: bool = typer.Option(False, "--check", help="Fail when a checked-in output differs.")) -> None:
    outputs = render_all()
    if check:
        stale = []
        for p, v in outputs.items():
            target = p if p.is_absolute() else ROOT / p
            rel = target.relative_to(REPO_ROOT).as_posix() if target.is_absolute() or str(p).startswith("/") else p.as_posix()
            if not target.exists() or target.read_text(encoding="utf-8") != v:
                stale.append(rel)
        if stale:
            typer.echo(f"Stale site outputs (run site builder): {', '.join(sorted(stale))}", err=True)
            raise typer.Exit(1)
        typer.echo(f"Site outputs current ({len(outputs)} files, {json.loads(outputs[Path('catalog.json')])['total']} items).")
        return
    for path in write_all():
        typer.echo(f"wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    app()
